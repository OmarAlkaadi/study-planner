-- ============================================================
-- Refresh-Tokens: länger angemeldet bleiben
-- Das kurzlebige Login-Token (JWT, 15 Minuten) wird über ein langlebiges Refresh-Token
-- (Standard 30 Tage, im httpOnly-Cookie) erneuert. Gespeichert wird nur der SHA-256-Hash.
-- Jede Erneuerung ersetzt das Refresh-Token (Rotation). Ungültig gewordene Tokens bekommen
-- revoked_at gesetzt; replaced_at zusätzlich nur, wenn sie durch Erneuern ersetzt wurden.
-- Taucht ein ersetztes Token wieder auf, wurde es vermutlich gestohlen.
-- ============================================================

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    expires_at  TIMESTAMP   NOT NULL,
    created_at  TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    revoked_at  TIMESTAMP,
    replaced_at TIMESTAMP
);

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
