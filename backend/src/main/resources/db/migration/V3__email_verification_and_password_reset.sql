-- ============================================================
-- E-Mail-Bestätigung und "Passwort vergessen"
-- ============================================================

-- Neue Konten müssen ihre E-Mail-Adresse bestätigen, bevor sie sich anmelden können.
-- Bereits vorhandene Konten (z. B. der Demo-Account) gelten als bestätigt.
ALTER TABLE users ADD COLUMN email_verified BOOLEAN DEFAULT FALSE NOT NULL;
UPDATE users SET email_verified = TRUE;

-- Einmal-Tokens für die Links in den E-Mails.
-- Gespeichert wird nur ein SHA-256-Hash des Tokens: Selbst wer die Datenbank lesen kann,
-- kann damit keine E-Mail bestätigen und kein Passwort zurücksetzen.
CREATE TABLE user_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    purpose    VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP   NOT NULL,
    used_at    TIMESTAMP,
    created_at TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_user_tokens_purpose CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET'))
);

CREATE INDEX idx_user_tokens_user ON user_tokens (user_id);
