-- ============================================================
-- Study Planner – Initiales Datenbankschema
-- Jede Tabelle gehört einem Benutzer (user_id), damit jeder
-- Student nur seine eigenen Daten sieht.
-- ============================================================

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Vorlesungen / Übungen / Praktika (wöchentlich wiederkehrend)
CREATE TABLE courses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name        VARCHAR(150) NOT NULL,
    lecturer    VARCHAR(150),
    room        VARCHAR(50),
    course_type VARCHAR(20)  NOT NULL,
    day_of_week VARCHAR(10)  NOT NULL,
    start_time  TIME         NOT NULL,
    end_time    TIME         NOT NULL,
    ects        INTEGER,
    color       VARCHAR(7),
    CONSTRAINT chk_courses_type CHECK (course_type IN ('VORLESUNG', 'UEBUNG', 'PRAKTIKUM', 'SEMINAR', 'SONSTIGES')),
    CONSTRAINT chk_courses_day CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT chk_courses_time CHECK (end_time > start_time),
    CONSTRAINT chk_courses_ects CHECK (ects IS NULL OR (ects >= 0 AND ects <= 30))
);

-- Klausuren gehören immer zu einem Kurs
CREATE TABLE exams (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    course_id BIGINT        NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
    title     VARCHAR(150)  NOT NULL,
    exam_date TIMESTAMP     NOT NULL,
    room      VARCHAR(50),
    notes     VARCHAR(1000),
    grade     NUMERIC(2, 1),
    CONSTRAINT chk_exams_grade CHECK (grade IS NULL OR (grade >= 1.0 AND grade <= 5.0))
);

-- Aufgaben mit Deadline (Kurs ist optional)
CREATE TABLE tasks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    course_id    BIGINT        REFERENCES courses (id) ON DELETE SET NULL,
    title        VARCHAR(150)  NOT NULL,
    description  VARCHAR(2000),
    due_date     DATE          NOT NULL,
    priority     VARCHAR(10)   NOT NULL,
    status       VARCHAR(15)   NOT NULL,
    created_at   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    CONSTRAINT chk_tasks_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT chk_tasks_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'DONE'))
);

-- Lerneinheiten für den Lernfortschritt
CREATE TABLE study_sessions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    course_id        BIGINT       NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
    session_date     DATE         NOT NULL,
    duration_minutes INTEGER      NOT NULL,
    topic            VARCHAR(200),
    CONSTRAINT chk_sessions_duration CHECK (duration_minutes > 0 AND duration_minutes <= 1440)
);

-- Indizes für die häufigsten Abfragen
CREATE INDEX idx_courses_user ON courses (user_id);
CREATE INDEX idx_exams_user_date ON exams (user_id, exam_date);
CREATE INDEX idx_exams_course ON exams (course_id);
CREATE INDEX idx_tasks_user_due ON tasks (user_id, due_date);
CREATE INDEX idx_tasks_course ON tasks (course_id);
CREATE INDEX idx_sessions_user_date ON study_sessions (user_id, session_date);
CREATE INDEX idx_sessions_course ON study_sessions (course_id);
